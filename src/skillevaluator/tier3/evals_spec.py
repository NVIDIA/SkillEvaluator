@dataclass
class CheckResult:
    path: str
    status: str  # "ok", "missing", "warning", "error"
    message: str


def validate_skillevaluators(skill_path: Path) -> list[CheckResult]:
    """Validate a skill's evals/ directory against the spec.

    Returns a list of check results — one per spec entry, plus any
    additional checks (dataset field validation, Dockerfile rules, etc.).
    """
    results: list[CheckResult] = []

    # 1. Required dataset
    _check_dataset(skill_path, results)

    # 2. Walk spec entries
    for spec in EVALS_SPEC:
        if spec.rel_path == "evals/evals.json":
            continue  # handled above
        if spec.scope == Scope.OUTPUT:
            continue  # not something the developer authors

        if "<subdirs>" in spec.rel_path:
            continue  # wildcard — not individually checkable

        target = skill_path / spec.rel_path.rstrip("/")
        if spec.kind == "dir":
            if target.is_dir():
                results.append(CheckResult(spec.rel_path, "ok", spec.description))
            # Dirs are always optional — don't warn about absence
        elif target.exists():
            results.append(CheckResult(spec.rel_path, "ok", spec.description))
            _run_file_checks(target, spec, results)
            # Optional files — no warning for absence

    # 3. scripts/ deps
    for spec in SCRIPTS_SPEC:
        target = skill_path / spec.rel_path
        if target.exists():
            results.append(CheckResult(spec.rel_path, "ok", spec.description))

    # 4. Check for unrecognised files in evals/
    _check_unrecognised(skill_path, results)

    return results


def validate_tier3_source(skill_path: Path) -> tuple[str, list[CheckResult]]:
    """Resolve and validate the Tier 3 source selected by a skill."""
    from skillevaluator.tier3.dataset_utils import find_eval_file
    from skillevaluator.tier3.evals_config import EvalsConfigError, load_evals_config

    try:
        config, config_path = load_evals_config(skill_path)
    except EvalsConfigError as exc:
        return "invalid", [CheckResult("evals/config.yml", "error", str(exc))]

    configured = str((config.get("harbor") or {}).get("task_source") or "auto")
    evals_file = find_eval_file(skill_path)
    native_dir = skill_path / "evals" / "harbor"

    if configured == "auto":
        if evals_file is not None:
            source = "evals_json"
        elif native_dir.is_dir():
            source = "native_harbor"
        else:
            return "missing", [
                CheckResult(
                    "evals/",
                    "error",
                    "No Tier 3 task source found. Add evals/evals.{json,jsonl,yaml,yml} "
                    "or an evals/harbor native task source.",
                )
            ]
    else:
        source = configured

    if source == "evals_json":
        if evals_file is None:
            selected_at = str(config_path) if config_path else "the default configuration"
            return source, [
                CheckResult(
                    "evals/evals.json",
                    "error",
                    f"Tier 3 source evals_json was selected by {selected_at}, but no supported eval dataset exists.",
                )
            ]
        results = [CheckResult(str(evals_file.relative_to(skill_path)), "ok", "Tier 3 eval dataset found.")]
        _validate_dataset_contents(evals_file, results)
        return source, results

    if source == "native_harbor":
        if not native_dir.is_dir():
            return source, [
                CheckResult(
                    "evals/harbor/",
                    "error",
                    "Tier 3 source native_harbor was selected, but evals/harbor does not exist.",
                )
            ]
        return source, validate_harbor_contract(skill_path)

    return "invalid", [CheckResult("evals/config.yml", "error", f"Unsupported Tier 3 task source: {source}")]


def validate_harbor_contract(skill_path: Path) -> list[CheckResult]:
    """Validate the BYOT Harbor task contract without mutating user files."""
    results: list[CheckResult] = []
    harbor_dir = skill_path / "evals" / "harbor"
    top_level_graders = [
        skill_path / "evals" / "grader.py",
        skill_path / "evals" / "grader.sh",
    ]
    existing_top_level_graders = [path for path in top_level_graders if path.exists()]

    if not harbor_dir.is_dir():
        if existing_top_level_graders:
            for grader in existing_top_level_graders:
                rel = f"evals/{grader.name}"
                results.append(CheckResult(rel, "ok", "Top-level custom grader found for BYOG generated tasks."))
                _validate_custom_grader_file(grader, rel, results)
            return results
        results.append(
            CheckResult(
                "evals/harbor/",
                "error",
                "BYOT Harbor task source missing. Create one with: skillevaluator init-harbor-task <path>, "
                "or create a top-level BYOG grader with: skillevaluator init-custom-grader <path>",
            )
        )
        return results

    results.append(CheckResult("evals/harbor/", "ok", "BYOT Harbor task source found."))

    dataset_toml = harbor_dir / "dataset.toml"
    task_names: list[str] = []
    if dataset_toml.exists():
        results.append(CheckResult("evals/harbor/dataset.toml", "ok", "Harbor dataset manifest found."))
        try:
            import tomllib

            data = tomllib.loads(dataset_toml.read_text(encoding="utf-8"))
            tasks = data.get("tasks", [])
            if isinstance(tasks, list):
                task_names = [str(task.get("name")) for task in tasks if isinstance(task, dict) and task.get("name")]
            if not task_names:
                results.append(
                    CheckResult(
                        "evals/harbor/dataset.toml",
                        "warning",
                        "No [[tasks]] entries found. Harbor may have no cases to run.",
                    )
                )
        except Exception as e:
            results.append(CheckResult("evals/harbor/dataset.toml", "error", f"Invalid TOML: {e}"))
    else:
        results.append(CheckResult("evals/harbor/dataset.toml", "error", "Harbor dataset manifest is required."))

    case_dirs = [path for path in sorted(harbor_dir.iterdir()) if path.is_dir() and not path.name.startswith(".")]
    if not case_dirs:
        results.append(
            CheckResult(
                "evals/harbor/<case>/",
                "error",
                "No Harbor case directories found.",
            )
        )

    for case_dir in case_dirs:
        rel = f"evals/harbor/{case_dir.name}"
        task_toml = case_dir / "task.toml"
        instruction = case_dir / "instruction.md"
        grader = case_dir / "tests" / "grader.py"
        shell_grader = case_dir / "tests" / "grader.sh"
        test_sh = case_dir / "tests" / "test.sh"
        dockerfile = case_dir / "environment" / "Dockerfile"

        if task_toml.exists():
            results.append(CheckResult(f"{rel}/task.toml", "ok", "Harbor task definition found."))
            try:
                import tomllib

                tomllib.loads(task_toml.read_text(encoding="utf-8"))
            except Exception as e:
                results.append(CheckResult(f"{rel}/task.toml", "error", f"Invalid TOML: {e}"))
        else:
            results.append(CheckResult(f"{rel}/task.toml", "error", "Harbor task definition is required."))

        if instruction.exists():
            results.append(CheckResult(f"{rel}/instruction.md", "ok", "Task instruction found."))
        else:
            results.append(CheckResult(f"{rel}/instruction.md", "warning", "No instruction.md found."))

        if grader.exists() or shell_grader.exists() or test_sh.exists():
            if grader.exists():
                results.append(CheckResult(f"{rel}/tests/grader.py", "ok", "Custom grader entrypoint found."))
                _validate_custom_grader_file(grader, f"{rel}/tests/grader.py", results)
            if shell_grader.exists():
                results.append(CheckResult(f"{rel}/tests/grader.sh", "ok", "Custom shell grader entrypoint found."))
                _validate_custom_grader_file(shell_grader, f"{rel}/tests/grader.sh", results)
            if test_sh.exists():
                results.append(CheckResult(f"{rel}/tests/test.sh", "ok", "Verifier shell entrypoint found."))
        else:
            results.append(
                CheckResult(
                    f"{rel}/tests/",
                    "warning",
                    "No custom grader/test entrypoint found. SkillEvaluator can inject default grading when enabled.",
                )
            )

        if dockerfile.exists():
            text = dockerfile.read_text(encoding="utf-8", errors="ignore")
            if "COPY" in text.upper() and "skills" in text.lower():
                results.append(
                    CheckResult(
                        f"{rel}/environment/Dockerfile",
                        "warning",
                        "Dockerfile appears to copy skills. SkillEvaluator stages target/baseline skills in generated copies; "
                        "source BYOT tasks should avoid hardcoding the target skill.",
                    )
                )

    evals_file = skill_path / "evals" / "evals.json"
    if evals_file.exists() and case_dirs:
        try:
            from .dataset_utils import load_dataset_entries

            entry_ids = {str(entry.get("id")) for entry in load_dataset_entries(evals_file)}
            missing = [
                case_dir.name
                for case_dir in case_dirs
                if case_dir.name not in entry_ids and f"nvidia/{case_dir.name}" not in task_names
            ]
            if missing:
                results.append(
                    CheckResult(
                        "evals/evals.json",
                        "warning",
                        "BYOT case metadata not found for: "
                        + ", ".join(missing)
                        + ". Default grading needs matching evals.json ids unless grading.mode=custom_only.",
                    )
                )
        except Exception as e:
            results.append(CheckResult("evals/evals.json", "warning", f"Could not check BYOT metadata ids: {e}"))

    return results


def _check_dataset(skill_path: Path, results: list[CheckResult]) -> bool:
    """Check for the required dataset file. Returns True if found."""
    evals_dir = skill_path / "evals"
    if not evals_dir.is_dir():
        results.append(
            CheckResult(
                "evals/",
                "missing",
                "No evals/ directory found. Create one with: skillevaluator create-eval-dataset <path>",
            )
        )
        return False

    for ext in DATASET_EXTENSIONS:
        candidate = evals_dir / f"evals{ext}"
        if candidate.exists():
            results.append(
                CheckResult(
                    f"evals/evals{ext}",
                    "ok",
                    f"Dataset found ({candidate.stat().st_size} bytes).",
                )
            )
            _validate_dataset_contents(candidate, results)
            return True

    results.append(
        CheckResult(
            "evals/evals.json",
            "error",
            "REQUIRED dataset file missing. Accepted names: "
            + ", ".join(f"evals{e}" for e in DATASET_EXTENSIONS)
            + ". Generate with: skillevaluator create-eval-dataset <path>",
        )
    )
    return False


def _validate_dataset_contents(path: Path, results: list[CheckResult]) -> None:
    """Validate the contents of a dataset file."""
    from .dataset_utils import load_dataset_entries_with_format

    try:
        entries, dataset_format = load_dataset_entries_with_format(path)
    except Exception as e:
        results.append(CheckResult(str(path), "error", f"Cannot parse dataset: {e}"))
        return

    if dataset_format == "legacy":
        results.append(
            CheckResult(
                str(path.name),
                "warning",
                "Deprecated eval dataset format: legacy flat entries are still accepted, "
                "but new datasets should use the agentskills.io shape "
                '{"skill_name": "...", "evals": [{"id": "...", "prompt": "...", '
                '"expected_output": "..."}]}.',
            )
        )

    if not entries:
        results.append(CheckResult(str(path), "error", "Dataset is empty (0 entries)."))
        return

    results.append(
        CheckResult(
            str(path.name),
            "ok",
            f"Dataset has {len(entries)} {'entry' if len(entries) == 1 else 'entries'}.",
        )
    )

    try:
        validate_case_ids(entry.get("id") for entry in entries)
    except ValueError as exc:
        results.append(CheckResult(str(path.name), "error", str(exc)))

    skill_path = path.parent.parent
    skill_has_scripts = any((skill_path / "scripts").glob("*.py"))

    for i, entry in enumerate(entries):
        entry_id = entry.get("id", f"<index {i}>")
        required_fields = AGENTSKILLS_REQUIRED_FIELDS if dataset_format == "agentskills" else DATASET_REQUIRED_FIELDS
        missing_required = required_fields - set(entry.keys())
        if missing_required:
            results.append(
                CheckResult(
                    f"entry {entry_id}",
                    "error",
                    f"Missing required fields: {', '.join(sorted(missing_required))}",
                )
            )
        missing_recommended = DATASET_RECOMMENDED_FIELDS - set(entry.keys())
        if dataset_format == "legacy" and missing_recommended:
            results.append(
                CheckResult(
                    f"entry {entry_id}",
                    "warning",
                    f"Missing recommended fields: {', '.join(sorted(missing_recommended))}",
                )
            )
        if dataset_format == "legacy" and "expected_script" not in entry and skill_has_scripts:
            results.append(
                CheckResult(
                    f"entry {entry_id}",
                    "warning",
                    "expected_script is missing, but this skill has scripts. "
                    "Add expected_script or set expected_script: null if no script should be run.",
                )
            )


def _run_file_checks(target: Path, spec: EntrySpec, results: list[CheckResult]) -> None:
    """Run spec-specific validation on an existing file."""
    if spec.rel_path in ("evals/grader.py", "evals/grader.sh"):
        _validate_custom_grader_file(target, spec.rel_path, results)

    if "Dockerfile" in spec.rel_path:
        size = target.stat().st_size
        if size > DOCKERFILE_MAX_BYTES:
            results.append(
                CheckResult(
                    spec.rel_path,
                    "error",
                    f"Dockerfile exceeds {DOCKERFILE_MAX_BYTES // 1000}KB limit ({size} bytes).",
                )
            )
        else:
            content = target.read_text(encoding="utf-8")
            lines = [ln.strip() for ln in content.splitlines() if ln.strip() and not ln.strip().startswith("#")]
            if not lines or not lines[0].upper().startswith("FROM"):
                results.append(
                    CheckResult(
                        spec.rel_path,
                        "error",
                        "Dockerfile must start with a FROM instruction.",
                    )
                )
            for i, ln in enumerate(content.splitlines(), 1):
                upper = ln.strip().upper()
                if upper.startswith("COPY") and "environment/" in ln:
                    results.append(
                        CheckResult(
                            spec.rel_path,
                            "error",
                            f"Line {i}: COPY references 'environment/' but the build context IS "
                            f"environment/. Use relative paths (e.g. 'COPY skills/' not "
                            f"'COPY environment/skills/').",
                        )
                    )
                    break

    if "mcp_servers.toml" in spec.rel_path:
        _validate_mcp_toml(target, results)

    if spec.rel_path in ("evals/config.yml", "evals/config.yaml"):
        _validate_evals_config(target, results)


def _validate_custom_grader_file(path: Path, rel_path: str, results: list[CheckResult]) -> None:
    text = path.read_text(encoding="utf-8", errors="ignore")
    if "reward.json" not in text and "reward.txt" not in text:
        results.append(
            CheckResult(
                rel_path,
                "warning",
                "Custom graders should write /logs/verifier/reward.json or reward.txt.",
            )
        )
    if path.suffix == ".py":
        try:
            compile(text, str(path), "exec")
        except SyntaxError as e:
            results.append(CheckResult(rel_path, "error", f"Invalid Python custom grader: {e.msg}"))


def _validate_evals_config(path: Path, results: list[CheckResult]) -> None:
    try:
        from .evals_config import load_evals_config

        load_evals_config(path.parent.parent)
    except Exception as e:
        results.append(CheckResult(str(path), "error", f"Invalid evals config: {e}"))


def _validate_mcp_toml(path: Path, results: list[CheckResult]) -> None:
    try:
        import tomllib
    except ImportError:
        try:
            import tomli as tomllib  # type: ignore[no-redef]
        except ImportError:
            results.append(CheckResult(str(path), "warning", "Cannot validate: tomllib/tomli not available."))
            return

    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except Exception as e:
        results.append(CheckResult(str(path), "error", f"Invalid TOML: {e}"))
        return

    servers = data.get("mcp_servers", [])
    if not isinstance(servers, list):
        results.append(
            CheckResult(
                str(path),
                "error",
                f"Expected [[mcp_servers]] array of tables, got {type(servers).__name__}.",
            )
        )
        return

    for i, s in enumerate(servers):
        if not isinstance(s, dict) or "name" not in s:
            results.append(
                CheckResult(
                    str(path),
                    "error",
                    f"Entry {i}: missing 'name' field.",
                )
            )
            continue
        if "url" not in s and "command" not in s:
            results.append(
                CheckResult(
                    str(path),
                    "error",
                    f"Entry '{s['name']}': needs 'url' or 'command'.",
                )
            )
        elif "command" in s and s.get("transport") != "stdio":
            results.append(
                CheckResult(
                    str(path),
                    "warning",
                    f"Entry '{s['name']}': command-based server should set transport = \"stdio\". "
                    f'Harbor defaults to "sse" which requires a url. '
                    f"The adapter will auto-infer this, but explicit is better.",
                )
            )


def _check_unrecognised(skill_path: Path, results: list[CheckResult]) -> None:
    """Warn about files in evals/ that the toolchain doesn't recognise."""
    evals_dir = skill_path / "evals"
    if not evals_dir.is_dir():
        return

    known_top_level = {
        "evals.json",
        "evals.jsonl",
        "evals.yaml",
        "evals.yml",
        "config.yml",
        "config.yaml",
        "EVAL.md",
        "files",
        "environment",
        "results",
        "harbor",
        "grader.py",
        "grader.sh",
    }

    for child in sorted(evals_dir.iterdir()):
        if child.name.startswith(".") or child.name == "__pycache__":
            continue
        if child.name not in known_top_level:
            results.append(
                CheckResult(
                    f"evals/{child.name}",
                    "warning",
                    "Unrecognised file/directory. The toolchain will ignore this.",
                )
            )

    env_dir = evals_dir / "environment"
    if env_dir.is_dir():
        known_env = {"Dockerfile", "docker-compose.yaml", "docker-compose.yml", "mcp_servers.toml"}
        for child in sorted(env_dir.iterdir()):
            if child.name.startswith(".") or child.name == "__pycache__":
                continue
            if child.name not in known_env and not child.is_dir():
                results.append(
                    CheckResult(
                        f"evals/environment/{child.name}",
                        "warning",
                        "Unrecognised file in environment/. "
                        "Only Dockerfile, docker-compose.yaml, mcp_servers.toml, and subdirectories are used.",
                    )
                )
