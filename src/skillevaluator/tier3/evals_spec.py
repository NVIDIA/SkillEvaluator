"""
Single source of truth for the evals/ directory structure.

Every file and directory that the SkillEvaluator toolchain recognises inside a skill's
``evals/`` directory is declared here.  This module is consumed by:

  - ``skillevaluator info evals``  — prints the annotated tree for discovery
  - ``skillevaluator validate``    — checks a skill directory against the spec
  - Runtime code (adapter, runner)   — can import constants instead of hard-coding paths
"""

