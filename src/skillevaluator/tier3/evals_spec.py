# ---------------------------------------------------------------------------


class Requirement(Enum):
    REQUIRED = "REQUIRED"
    OPTIONAL = "optional"


class Scope(Enum):
    HARBOR = "Harbor"
    OUTPUT = "output"  # generated by evaluation runs, not authored


@dataclass
class EntrySpec:
    """One file or directory in the evals/ tree."""

    rel_path: str
    kind: str  # "file" or "dir"
    requirement: Requirement
    scope: Scope
    description: str
    formats: list[str] = field(default_factory=list)
    validation_notes: list[str] = field(default_factory=list)
    example: str = ""


