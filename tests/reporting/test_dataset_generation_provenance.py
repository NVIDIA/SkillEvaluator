from __future__ import annotations

from io import StringIO

import pytest
from rich.console import Console

from skillevaluator.evaluation.tier3_report import build_agent_eval_payload
from skillevaluator.models import ValidationResult
from skillevaluator.reporting.benchmark import BenchmarkReporter
from skillevaluator.reporting.cli import CLIReporter
from skillevaluator.reporting.html import HTMLReporter
from skillevaluator.tier3.harbor.metrics import DEFAULT_METRICS
from skillevaluator.tier3.result_display import render_result


def _generation(mode: str) -> dict:
    if mode == "llm":
        return {
            "mode": mode,
            "grounding": "skill",
            "review_state": "unreviewed",
            "needs_review_count": 2,
        }
    return {
        "mode": mode,
        "grounding": "skill",
        "review_state": "needs_review",
        "needs_review_count": 2,
        "fallback_reason": "public LLM provider is not configured",
    }


def _result(generation: dict | None) -> ValidationResult:
    agent = {
        "execution_status": "succeeded",
        "execution_errors": [],
        "expected_attempts": 1,
        "scored_attempts": 1,
        "with_skill": dict.fromkeys(DEFAULT_METRICS, 0.8),
        "metrics_with_skill": list(DEFAULT_METRICS),
        "overall_with_skill": 0.8,
        "rewards": [
            {
                "entry_id": "case-1",
                "metric_set": "skill-evaluator-default-v2",
                **dict.fromkeys(DEFAULT_METRICS, 0.8),
                "overall": 0.8,
            }
        ],
    }
    payload = build_agent_eval_payload(
        "sample-skill",
        {"opencode": agent},
        dataset=[{"id": "case-1", "prompt": "Do the task", "expected_output": "A result"}],
        dataset_provenance=generation,
        use_llm_judge=False,
    )
    assert payload is not None
    result = ValidationResult(validator_name="AGENT_EVAL", validator_description="Live evaluation")
    result.metadata["agent_eval"] = payload
    return result


def _render_validate_line(payload: dict) -> str:
    stream = StringIO()
    console = Console(file=stream, width=240, force_terminal=False, color_system=None)
    CLIReporter._print_agent_eval_tables(payload, console)
    return stream.getvalue()


@pytest.mark.parametrize(
    ("mode", "expected"),
    [
        (
            "template_requested",
            "Dataset: generated from templates (requested) — cases are generic starters; review before relying on scores; 2 cases need review",
        ),
        (
            "template_fallback",
            "Dataset: generated from templates (fallback: public LLM provider is not configured) — cases are generic starters; review before relying on scores; 2 cases need review",
        ),
        ("llm", "Dataset: generated by skill grounding, review state unreviewed; 2 cases need review"),
    ],
)
def test_provenance_renders_on_evaluate_validate_html_and_benchmark(mode: str, expected: str) -> None:
    result = _result(_generation(mode))
    payload = result.metadata["agent_eval"]

    evaluate = render_result({"execution_status": "succeeded", "dataset_provenance": _generation(mode)})
    validate = _render_validate_line(payload)
    html = HTMLReporter(include_timestamp=False, report_scope="tier3").render_all([result])
    benchmark = BenchmarkReporter(
        include_timestamp=False,
        report_scope="tier3",
        skill_name="sample-skill",
    ).render(result)

    assert expected in evaluate
    assert expected in validate
    assert expected in html
    assert expected in benchmark
    if mode.startswith("template"):
        assert "t3-dataset-provenance warning" in html


def test_missing_generation_record_renders_no_dataset_line() -> None:
    result = _result(None)
    payload = result.metadata["agent_eval"]

    evaluate = render_result({"execution_status": "succeeded"})
    validate = _render_validate_line(payload)
    html = HTMLReporter(include_timestamp=False, report_scope="tier3").render_all([result])
    benchmark = BenchmarkReporter(
        include_timestamp=False,
        report_scope="tier3",
        skill_name="sample-skill",
    ).render(result)

    assert "Dataset: generated" not in evaluate
    assert "Dataset: generated" not in validate
    assert "Dataset: generated" not in html
    assert "Dataset: generated" not in benchmark


def test_report_payload_preserves_paths_and_shortens_input_hashes() -> None:
    generation = {
        "mode": "llm",
        "grounding": "intent",
        "review_state": "unreviewed",
        "inputs": [{"kind": "eval_md", "path": "evals/EVAL.md", "sha256": "a" * 64}],
    }

    provenance = _result(generation).metadata["agent_eval"]["dataset_provenance"]

    assert provenance["inputs"] == [{"kind": "eval_md", "path": "evals/EVAL.md", "sha256": "a" * 12}]
